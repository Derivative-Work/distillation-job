"""Copy picked takes into public/ for Remotion and write config/picks_manifest.json (what exists under public/media).

Adapted from ../buy-it-on-margin/scripts/publish_picks.py. Stills: config/stills.json "kept" {item: seed or file stem}
-> public/media/picks/<item>.png. Clips: config/clips.json "kept" {clip: path} -> public/media/picks/<clip>.mp4.
src/Main.tsx renders a labelled placeholder for any shot whose media is not in the manifest.
Usage: python3 -I scripts/publish_picks.py
"""
import json
import shutil
from pathlib import Path

PUB = Path("public")
dst = PUB / "media/picks"; dst.mkdir(parents=True, exist_ok=True)
for item, k in json.load(open("config/stills.json")).get("kept", {}).items():
    if item.startswith("ref_"):
        continue
    src = Path(f"takes/stills/{item}/{k if isinstance(k, str) else f'{item}_s{k}'}.png")
    if src.exists():
        shutil.copy2(src, dst / f"{item}.png")
for clip, path in json.load(open("config/clips.json")).get("kept", {}).items():
    if Path(path).exists():
        shutil.copy2(path, dst / f"{clip}.mp4")
files = sorted(str(p.relative_to(PUB)) for p in (PUB / "media").rglob("*") if p.is_file() and "test" not in p.parts
               and p.suffix in (".png", ".mp4"))
import subprocess
frames = {f: int(subprocess.run(["ffprobe", "-v", "error", "-count_frames", "-select_streams", "v", "-show_entries",
          "stream=nb_read_frames", "-of", "csv=p=0", str(PUB / f)], capture_output=True, text=True).stdout.strip())
          for f in files if f.endswith(".mp4")}
json.dump({"_doc": "Generated by scripts/publish_picks.py: media present under public/media; clip frame counts.",
           "files": files, "frames": frames},
          open("config/picks_manifest.json", "w"), indent=1)
open("config/picks_manifest.json", "a").write("\n")
print(len(files), "files")
